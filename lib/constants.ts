// Helper to generate mock player lists
function generateMockPlayers(bullsCount: number, bearsCount: number): PlayerSlot[] {
  const players: PlayerSlot[] = [];
  const bullNames = ['ApeLonger', 'SatoshiSlayer', 'Moonshot99', 'ChadWhale', 'GreenCandle', 'HODLMaster', 'RocketRider', 'AlphaBull', 'DeFiKing', 'Gigachad', 'BullRun2026', 'PumpItUp', 'LeverageMax', 'DiamondHands', 'BullTitan'];
  const bearNames = ['ShortSqueeze', 'DumpDetector', 'BearClaw', 'GrimReaper', 'RedSea', 'Liquidator', 'ShortKing', 'SubZero', 'BearWhale', 'CrashBandit', 'FUDMaster', 'ZeroGrav', 'PutBuyer', 'ColdStorage', 'BearOverlord'];

  for (let i = 0; i < bullsCount; i++) {
    players.push({
      id: `bull-${i + 1}`,
      address: bullNames[i % bullNames.length],
      side: 'bulls',
      joinedAt: `${Math.max(1, 15 - i * 2)}m ago`,
    });
  }

  for (let i = 0; i < bearsCount; i++) {
    players.push({
      id: `bear-${i + 1}`,
      address: bearNames[i % bearNames.length],
      side: 'bears',
      joinedAt: `${Math.max(1, 14 - i * 2)}m ago`,
    });
  }

  return players;
}

